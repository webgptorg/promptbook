import { createHash, randomUUID } from 'node:crypto';
import { readFile, readdir, rm, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { PtbkError } from '../common/errors.js';
import { isImagePath } from '../ui/attachments.js';
import type { ComposedSegment } from '../ui/composer.js';
import { assertPrivate, createPrivateFile, ensurePrivateDirectory, readPrivateFile, writePrivateFile } from './files.js';

/** Maximum single upload size, including on the local client path. @private project onboarding */
export const ONBOARDING_FILE_BYTES = 16 * 1024 * 1024;

/** Total number of stored uploads before the owner has to remove some. */
const MAX_UPLOADS = 40;

/** An opaque identifier generated by this engine, never a file path. */
const FILE_ID = /^[a-f0-9-]{36}$/;

/** The contract's metadata for one staged upload. */
type Upload = {
    readonly id: string;
    readonly name: string;
    readonly contentType: string;
    readonly sizeBytes: number;
    readonly sha256: string;
    readonly purpose: 'upload';
    readonly agentId: null;
    readonly chatId: null;
    readonly runId: null;
    readonly scan: null;
    readonly versionCount: 1;
    readonly createdBy: string;
    readonly createdAt: string;
};

/** The private file capability of a pending initialization. @private project onboarding */
export class OnboardingFiles {
    public constructor(private readonly directory: string) {}

    /** Lists complete uploads; interrupted uploads never appear in the inventory. */
    public async list(): Promise<Upload[]> {
        await ensurePrivateDirectory(this.directory);
        const names = (await readdir(this.directory)).filter((name) => name.endsWith('.json') && FILE_ID.test(name.slice(0, -5)));
        const items = await Promise.all(names.map(async (name) => await this.get(name.slice(0, -5))));
        return items.filter((item): item is Upload => Boolean(item));
    }

    /** Loads metadata for one engine-issued file ID. */
    public async get(id: string): Promise<Upload | undefined> {
        if (!FILE_ID.test(id)) return undefined;
        const text = await readPrivateFile(this.directory, `${id}.json`);
        return text === undefined ? undefined : JSON.parse(text) as Upload;
    }

    /** Saves bytes first and publishes metadata last. */
    public async upload(name: string, file: Blob, createdBy: string): Promise<Upload> {
        if (file.size > ONBOARDING_FILE_BYTES) throw new PtbkError('The file exceeds the onboarding upload limit.', { kind: 'usage' });
        if (!name.trim() || /[\u0000-\u001f\u007f]/.test(name) || name.length > 255) throw new PtbkError('Enter a valid file name.', { kind: 'usage' });
        await ensurePrivateDirectory(this.directory);
        if ((await readdir(this.directory)).filter((entry) => FILE_ID.test(entry)).length >= MAX_UPLOADS) {
            throw new PtbkError('Remove some staged uploads before uploading another file.', { kind: 'usage' });
        }
        const id = randomUUID();
        const bytes = new Uint8Array(await file.arrayBuffer());
        const metadata: Upload = {
            id, name: name.trim(), contentType: file.type || 'application/octet-stream', sizeBytes: file.size,
            sha256: createHash('sha256').update(bytes).digest('hex'), purpose: 'upload', agentId: null, chatId: null,
            runId: null, scan: null, versionCount: 1, createdBy, createdAt: new Date().toISOString(),
        };
        await createPrivateFile(this.directory, id, bytes);
        try {
            await writePrivateFile(this.directory, `${id}.json`, JSON.stringify(metadata));
        } catch (error) {
            await rm(join(this.directory, id), { force: true });
            throw error;
        }
        return metadata;
    }

    /** Copies a file chosen by an authenticated local client to the same private upload store. */
    public async uploadLocal(path: string, name: string): Promise<Upload> {
        const source = await stat(path);
        if (!source.isFile() || source.size > ONBOARDING_FILE_BYTES) throw new PtbkError('Choose a regular file below the onboarding upload limit.', { kind: 'usage' });
        return await this.upload(name, new Blob([await readFile(path)]), 'project');
    }

    /** Resolves uploaded IDs in answer order without interpreting them as paths. */
    public async segments(ids: readonly string[]): Promise<ComposedSegment[] | undefined> {
        const uploads = await Promise.all(ids.map(async (id) => await this.get(id)));
        if (uploads.some((upload) => !upload)) return undefined;
        return uploads.map((upload) => ({
            type: 'attachment',
            kind: isImagePath(upload!.name) ? 'image' : 'file',
            path: join(this.directory, upload!.id),
            name: upload!.name,
        }));
    }

    /** Reads an immutable upload for a binary response. */
    public async content(id: string): Promise<Uint8Array | undefined> {
        if (!(await this.get(id))) return undefined;
        const path = join(this.directory, id);
        await assertPrivate(path, 'file');
        return await readFile(path);
    }

    /** Removes an upload once it is no longer referenced by an answer. */
    public async delete(id: string): Promise<void> {
        if (!(await this.get(id))) return;
        await rm(join(this.directory, `${id}.json`), { force: true });
        await rm(join(this.directory, id), { force: true });
    }
}
