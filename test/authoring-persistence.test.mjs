import assert from 'node:assert/strict';
import test from 'node:test';
import { spawn, execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, realpath, readFile, writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { git } from '../dist/coder/git.js';
import { runQueue } from '../dist/coder/engine.js';
import { initializeProject } from '../dist/coder/authoring.js';
import { resolveWorkspace } from '../dist/coder/workspace.js';

/** The real installed CLI must wait to save until a running task has persisted its own result. */
test('default add waits for active execution and creates a separate owned PTBK commit', { timeout: 30000 }, async t => {
    const root = await realpath(await mkdtemp(join(tmpdir(), 'ptbk authoring ')));
    t.after(() => rm(root, { recursive: true, force: true }));
    await git(root, ['init', '-q']); await git(root, ['config', 'user.name', 'Authoring Fixture']); await git(root, ['config', 'user.email', 'fixture@example.test']); await git(root, ['config', 'commit.gpgsign', 'false']);
    const workspace = await resolveWorkspace({ path: root }, true);
    await initializeProject(workspace);
    await writeFile(join(root, 'agents/developer.book'), 'Developer\nFROM Void\nCLOSED\n');
    await writeFile(join(root, 'tasks/active.book'), 'TASK Active work\nTASK ID active\nImplement the accepted result.\n');
    await git(root, ['add', '.']); await git(root, ['commit', '-qm', 'Fixture baseline']);
    await writeFile(join(root, 'user.txt'), 'Preserve unrelated staging.\n'); await git(root, ['add', '--', 'user.txt']);
    let entered, release;
    const started = new Promise(accept => { entered = accept; });
    const gate = new Promise(accept => { release = accept; });
    t.after(() => release());
    const execution = runQueue(workspace, { harness: 'openai-codex', gitChanges: 'ignore', runHarness: async request => {
        entered(); await gate; await writeFile(join(request.projectPath, 'result.txt'), 'Accepted result.\n'); return { outcome: 'success', exitCode: 0, output: 'Accepted.' };
    } });
    await started;
    const child = spawn(process.execPath, [fileURLToPath(new URL('../bin/ptbk.js', import.meta.url)), 'add', 'Queued authoring operation', '--raw', '--no-questions'], { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] });
    t.after(() => child.kill('SIGTERM'));
    let stderr = '';
    const queued = new Promise((accept, reject) => { child.stderr.on('data', chunk => { stderr += chunk; if (stderr.includes('Waiting for the active workspace writer')) accept(); }); child.once('error', reject); });
    const done = new Promise((accept, reject) => { child.once('error', reject); child.once('exit', code => code === 0 ? accept() : reject(Error(stderr))); });
    await queued; release();
    const result = await execution; await done;
    assert.equal(result.completed, 1); assert.equal(result.commits.length, 1);
    const subjects = (await git(root, ['log', '-2', '--format=%s'])).trim().split('\n');
    assert.deepEqual(subjects, ['PTBK: Add task - Queued authoring operation', 'PTBK: Active work']);
    const authorPaths = (await git(root, ['diff-tree', '--no-commit-id', '--name-only', '-r', 'HEAD'])).trim().split('\n');
    assert.equal(authorPaths.length, 1); assert.match(authorPaths[0], /^tasks\/.*\.book$/);
    assert.equal(await git(root, ['show', `${result.commits[0]}:result.txt`]), 'Accepted result.\n');
    assert.match(await git(root, ['show', `${result.commits[0]}:tasks/active.book`]), /TASK DONE/);
    assert.equal(await git(root, ['show', ':user.txt']), 'Preserve unrelated staging.\n');
    assert.equal(await readFile(join(root, 'user.txt'), 'utf8'), 'Preserve unrelated staging.\n');
    const configuration = JSON.parse(await readFile(join(root, 'ptbk.json'), 'utf8'));
    configuration.tunnel = { enabled: true, client: process.execPath };
    await writeFile(join(root, 'ptbk.json'), JSON.stringify(configuration));
    await git(root, ['commit', '-qm', 'Fixture connector reference', '--only', '--', 'ptbk.json']);
    const head = await git(root, ['rev-parse', 'HEAD']);
    const cli = fileURLToPath(new URL('../bin/ptbk.js', import.meta.url));
    const uncommitted = await promisify(execFile)(process.execPath, [cli, 'add', 'Uncommitted alias', '--commit=false', '--raw'], { cwd: root });
    assert.match(uncommitted.stderr, /uncommitted/); assert.equal(await git(root, ['rev-parse', 'HEAD']), head);
    const finite = await promisify(execFile)(process.execPath, [cli, 'run', '--tunnel=false', '--raw', '--git-changes', 'ignore'], { cwd: root });
    assert.match(finite.stdout, /Remote: disabled/);
    assert.equal(await git(root, ['rev-parse', 'HEAD']), head);

});
